//! The Ferman text model.
//!
//! ferman-text sits on ferman-core and ferman-fonts. It resolves PDF font resources into a
//! `PdfFont` (dictionary, program, encoding, ToUnicode, widths, vertical metrics), implements the
//! interpreter's `TextAdvance` trait, builds glyph runs, maps glyphs to Unicode, and rebuilds words,
//! lines, blocks, columns, alignment and reading order. It assigns block ids, answers hit tests,
//! decides editability, runs edit operations with line breaking, reflow and bidi, re-encodes text in
//! the font's own encoding and generates the replacement operators for one block, resolves missing
//! glyphs and overflow, extracts search text and keeps the edit journal (docs/ARCHITECTURE.md §2.3
//! and §6).
//!
//! An edit rewrites only the operators of the edited block; every other byte of the page content
//! stays identical (ADR 0005).
//!
//! # Planned modules
//!
//! The layout below follows docs/ARCHITECTURE.md §2.3; each module
//! arrives with the milestone that needs it.
//!
//! - `font`: `PdfFont` resolution and the `TextAdvance` implementation, positions from the PDF
//!   widths. M2.
//! - [`extract`] (since M2): [`page_text`], a page's text in reading order: fonts from the
//!   interpreter's resources, glyphs to Unicode (ToUnicode, then the encoding's glyph names),
//!   lines by baseline, right-to-left lines read back with the bidi algorithm, vertical columns.
//!   Since M3 each glyph has its font's ascent and descent and its [`GlyphLink`] (its show
//!   operator's span and its index in the show). `PdfFont`, `GlyphRun` and the `runs` module grow
//!   out of it with editing (M3).
//! - [`layout`] (since M3): [`text_page`], a page's [`PageText`]: [`TextBlock`]s of [`Line`]s
//!   with words, alignment and the justification method, columns, table cells, reading order,
//!   [`BlockId`]s and editability.
//! - [`search`] (since M2): [`find`] with [`SearchOptions`], folding Turkish case and accents as
//!   a2-4a and G61 ask; the index and match quads per page follow with the search job.
//! - [`hit`] (since M3): hit testing, caret stops by grapheme cluster, caret boxes, selection
//!   quads and selected text of a [`TextBlock`].
//! - [`editability`] (since M3): [`Editability`] with its [`NotEditableReason`] (docs/ARCHITECTURE.md
//!   §6.5), and the [`EditContext`] that brings the document's reasons in.
//! - [`rewrite`] (since M3): [`rewrite_block`], a block's new text re-encoded in its simple and
//!   composite fonts as the [`Splice`]s that replace its changed lines' operators, with the
//!   state invariant; a character no font of its line draws is reported, never substituted. The
//!   standard 14 fonts' widths come from `standard14`, generated by `tools/standard14`.
//! - `edit`: `EditOp` and `BlockEditor`; line breaking and reflow on top of `rewrite`. M3.
//! - `plans`: `MissingGlyphPlan` and `OverflowPlan`, with the amounts computed for the block
//!   (ADR 0006, §6.7 and §6.8). M3.
//! - `journal`: the edit journal behind the review list. M3.
