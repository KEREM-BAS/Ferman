String _chars(String hex) => String.fromCharCodes([
  for (final unit in hex.trim().split(' ').where((u) => u.isNotEmpty))
    int.parse(unit, radix: 16),
]);

void main() {
  test('matches ICU on context- and language-dependent strings', () {
    final lines = _icuCases.trim().split('\n');
    expect(lines, hasLength(160));
    for (final line in lines) {
      final [locale, input, upper, lower] = line.split(';');
      final casing = LocaleCasing.forLanguage(locale.trim());
      final text = _chars(input);
      expect(casing.upper(text), _chars(upper), reason: line);
      expect(casing.lower(text), _chars(lower), reason: line);
    }
  });
}
