/// Emits the generated `IconName` enum for the Flutter app.
library;

import 'package:icons/src/design_icons.dart';
import 'package:icons/src/directional.dart';
import 'package:icons/src/errors.dart';

/// Where the enum is written, relative to the repository root.
const String enumPath = 'app/lib/design/icons/icon_name.g.dart';

/// Where the SVG files live, relative to the repository root. They are the
/// exported, provenance-tracked set; the app paints from the generated
/// element data instead of loading them.
const String assetsDir = 'app/assets/icons';

/// Dart reserved words, which cannot name an enum value.
const Set<String> _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', //
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', 'finally',
  'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with',
};

/// Members the enum declares or inherits, which a value cannot shadow.
const Set<String> _taken = {
  'id', 'directional', 'elements', 'fromId', 'values', 'index', 'name', //
  'hashCode', 'runtimeType', 'toString', 'noSuchMethod',
};

/// The Dart identifier for an icon name: `align-center` → `alignCenter`,
/// `grid-2x2` → `grid2x2`.
String dartIdentifier(String name) {
  final parts = name.split('-');
  final id =
      parts.first +
      parts.skip(1).map((s) => s[0].toUpperCase() + s.substring(1)).join();
  if (!RegExp(r'^[a-z][A-Za-z0-9]*$').hasMatch(id) ||
      _reserved.contains(id) ||
      _taken.contains(id)) {
    throw IconsException('Icon "$name" has no usable Dart name ("$id").');
  }
  return id;
}

/// Returns the unformatted source of `icon_name.g.dart` for [icons].
String emitIconEnum(List<DesignIcon> icons) {
  final seen = <String, String>{};
  for (final icon in icons) {
    final id = dartIdentifier(icon.name);
    final other = seen[id];
    if (other != null) {
      throw IconsException('"$other" and "${icon.name}" both map to "$id".');
    }
    seen[id] = icon.name;
  }
  final unknown = directionalIcons.keys.where(
    (name) => !icons.any((i) => i.name == name),
  );
  if (unknown.isNotEmpty) {
    throw IconsException('Directional icons not in the set: $unknown.');
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tools/icons from the design export. Do not edit')
    ..writeln('// by hand; run (cd tools/icons && dart run).')
    ..writeln()
    ..writeln('/// The ${icons.length} icons of the Ferman design system.')
    ..writeln('///')
    ..writeln("/// Each value is drawn from the design's exact path data:")
    ..writeln('/// `elements` in `icon_data.g.dart`, stroked 1.5 wide in the')
    ..writeln('/// icon colour (ADR 0013). Values follow the design-system')
    ..writeln('/// names in lower camel case; [id] keeps the original name.')
    ..writeln('enum IconName {');
  for (final icon in icons) {
    final id = dartIdentifier(icon.name);
    final flip = directionalIcons.containsKey(icon.name);
    out
      ..writeln(
        '  /// `${icon.name}`${flip ? ', mirrored in right-to-left' : ''}.',
      )
      ..writeln("  $id('${icon.name}'${flip ? ', directional: true' : ''}),");
  }
  out
    ..writeln('  ;')
    ..writeln()
    ..writeln('  new(this.id, {this.directional = false});')
    ..writeln()
    ..writeln('  /// The design-system name, such as `chevron-right`.')
    ..writeln('  final String id;')
    ..writeln()
    ..writeln('  /// Whether the design mirrors this icon in right-to-left')
    ..writeln('  /// layouts (chevrons, arrows, undo and redo, skip back and')
    ..writeln('  /// forward).')
    ..writeln('  final bool directional;')
    ..writeln()
    ..writeln('  /// The icon whose design-system name is [id], or `null`.')
    ..writeln('  static IconName? fromId(String id) => _byId[id];')
    ..writeln()
    ..writeln('  static final Map<String, IconName> _byId = {')
    ..writeln('    for (final icon in values) icon.id: icon,')
    ..writeln('  };')
    ..writeln('}');
  return out.toString();
}
