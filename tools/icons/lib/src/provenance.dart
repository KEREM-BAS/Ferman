/// Where the tool records which releases match each icon, relative to the
/// repository root. Written by `--lucide`, read by every other run.
const String matchesPath = 'tools/icons/lucide_matches.json';

/// What the provenance table says for the one glyph no release draws.
const String fermanDesign = 'Ferman design';

/// The lower-case hex SHA-256 of an icon's [markup] (its UTF-8 bytes), which
/// the matches file records so that a changed glyph is compared again.
String markupSha256(String markup) =>
    sha256.convert(utf8.encode(markup)).toString();

/// Encodes [matches] (icon → matching versions) for [icons] as the committed
/// JSON file, one icon per line so a changed match shows as a one-line diff.
///
/// Each entry records the [markupSha256] of the icon's markup next to its
/// releases.
String encodeMatches(
  Map<String, List<String>> matches,
  List<DesignIcon> icons,
) {
  final markup = {for (final i in icons) i.name: i.markup};
  final names = matches.keys.toList()..sort();
  final out = StringBuffer()
    ..writeln('{')
    ..writeln(
      '  "comment": "Generated by tools/icons (dart run icons --lucide <dir>). '
      'For each design icon, the SHA-256 of its markup and the pinned '
      'lucide-static releases whose icon of the same name has the same '
      'geometry, in preference order. A changed markup hash means the glyph '
      'must be compared again with --lucide.",',
    )
    ..writeln('  "releases": ${jsonEncode(_pinnedVersions)},')
    ..writeln('  "icons": {');
  for (final (i, name) in names.indexed) {
    final source = markup[name];
    if (source == null) {
      throw IconsException('No markup for the matched icon "$name".');
    }
    final comma = i == names.length - 1 ? '' : ',';
    out.writeln(
      '    ${jsonEncode(name)}: {"sha256": "${markupSha256(source)}", '
      '"releases": ${jsonEncode(matches[name])}}$comma',
    );
  }
  out
    ..writeln('  }')
    ..writeln('}');
  return out.toString();
}

List<String> get _pinnedVersions => [for (final r in lucideReleases) r.version];

const String _rerun =
    'run (cd tools/icons && dart run icons --lucide ../../build/lucide)';

/// Decodes the committed matches file and checks that it was made for the
/// pinned releases and covers exactly [icons] with their current markup.
Map<String, List<String>> decodeMatches(String json, List<DesignIcon> icons) {
  final Object? data;
  try {
    data = jsonDecode(json);
  } on FormatException catch (error) {
    throw IconsException('$matchesPath is not valid JSON: ${error.message}');
  }
  if (data is! Map<String, Object?> ||
      data['releases'] is! List<Object?> ||
      data['icons'] is! Map<String, Object?>) {
    throw IconsException('$matchesPath does not have the expected shape.');
  }
  final releases = (data['releases']! as List<Object?>).cast<String>();
  final pinned = _pinnedVersions;
  if (releases.join(',') != pinned.join(',')) {
    throw IconsException(
      '$matchesPath was made for releases $releases, not $pinned; $_rerun.',
    );
  }
  final raw = data['icons']! as Map<String, Object?>;
  final matches = <String, List<String>>{};
  final hashes = <String, String>{};
  for (final MapEntry(key: name, value: entry) in raw.entries) {
    final versions = entry is Map<String, Object?> ? entry['releases'] : null;
    final hash = entry is Map<String, Object?> ? entry['sha256'] : null;
    if (hash is! String ||
        versions is! List<Object?> ||
        versions.any((v) => v is! String || !pinned.contains(v))) {
      throw IconsException('$matchesPath: bad entry for "$name".');
    }
    matches[name] = versions.cast<String>();
    hashes[name] = hash;
  }
  final expected = {for (final i in icons) i.name};
  final missing = expected.difference(matches.keys.toSet());
  final extra = matches.keys.toSet().difference(expected);
  if (missing.isNotEmpty || extra.isNotEmpty) {
    throw IconsException(
      '$matchesPath is out of date (missing: ${missing.toList()..sort()}, '
      'extra: ${extra.toList()..sort()}); $_rerun.',
    );
  }
  final changed = [
    for (final icon in icons)
      if (hashes[icon.name] != markupSha256(icon.markup)) icon.name,
  ];
  if (changed.isNotEmpty) {
    throw IconsException(
      '$matchesPath: the path data of $changed changed since the matches '
      'were computed, so their provenance is unknown; $_rerun.',
    );
  }
  return matches;
}

/// The source the provenance table names for an icon with [versions]
/// matching: the first matching release, or [fermanDesign].
String sourceLabel(List<String> versions) =>
    versions.isEmpty ? fermanDesign : 'Lucide ${versions.first}';

/// Renders `app/assets/icons/PROVENANCE.md`.
String renderProvenance(
  List<DesignIcon> icons,
  Map<String, List<String>> matches,
) {
  final groups = licenseGroups();
  final counts = <String, int>{};
  for (final icon in icons) {
    final label = sourceLabel(matches[icon.name]!);
    counts[label] = (counts[label] ?? 0) + 1;
  }
  final order = [
    for (final r in lucideReleases) r.label,
    fermanDesign,
  ].where(counts.containsKey);
  final bundle = icons.where((i) => i.origin == IconOrigin.bundle).length;
  final additions = icons.length - bundle;
  String versionsList(List<LucideRelease> releases) =>
      releases.map((r) => r.version).join(', ');

  final out = StringBuffer()
    ..writeln('<!-- Generated by tools/icons. Do not edit by hand. -->')
    ..writeln()
    ..writeln('# Icon provenance')
    ..writeln()
    ..writeln(
      "The ${icons.length} icons in this folder are the design's exact path "
      'data: $bundle from `ICON_PATHS` in `$bundlePath` and $additions from '
      '`$additionsPath`, which the design merges into `ICON_PATHS` at run '
      "time. Each file wraps the design's child elements, byte for byte, in "
      'a 24 × 24 SVG drawn with a 1.5 px `currentColor` stroke and round '
      'caps and joins, as the design system draws its icons (ADR 0013, G04, '
      'G60). The app does not load these files: it paints the same elements '
      'from `$dataPath`, which tools/icons generates from the same source.',
    )
    ..writeln()
    ..writeln('## Licences')
    ..writeln()
    ..writeln(
      'Lucide is licensed under ISC. Portions of Lucide derive from Feather '
      'and are licensed under MIT (Cole Bemis). The licence files below are '
      'the `package/LICENSE` files of the lucide-static npm releases, copied '
      'verbatim:',
    )
    ..writeln();
  for (final group in groups) {
    final first = group.releases.first;
    final others = group.releases.skip(1).toList();
    out.writeln(
      '- `${group.fileName}`: lucide-static ${first.version}'
      '${others.isEmpty ? '' : ', byte-identical to ${versionsList(others)}'}.',
    );
  }
  out
    ..writeln()
    ..writeln(
      'The newest file lists the Feather-derived icons and carries the MIT '
      'text. The one glyph that matches no Lucide release is drawn for '
      'Ferman and is covered by the project licence; it stays pending until '
      'the design re-export settles it (Q11).',
    )
    ..writeln()
    ..writeln('## How the source is found')
    ..writeln()
    ..writeln(
      'Each icon is compared with the file of the same name in the pinned '
      'lucide-static releases ${versionsList(lucideReleases)} (npm tarballs '
      'verified by their integrity hashes). Two drawings match when they '
      'have the same elements in the same order with the same attributes; '
      'attribute order and whitespace do not count. The first matching '
      'release in that order is the source. `$matchesPath` records the '
      'matches with the SHA-256 of each glyph, and a run without the '
      'tarballs stops when a glyph has changed since. "Mirrors in RTL" '
      'marks the icons the design flips in right-to-left layouts.',
    )
    ..writeln()
    ..writeln('| Source | Icons |')
    ..writeln('|---|---|');
  for (final label in order) {
    out.writeln('| $label | ${counts[label]} |');
  }
  out
    ..writeln('| Total | ${icons.length} |')
    ..writeln()
    ..writeln('## Icons')
    ..writeln()
    ..writeln(
      '| Icon | Design source | Matching releases | Source | Mirrors in RTL |',
    )
    ..writeln('|---|---|---|---|---|');
  for (final icon in icons) {
    final versions = matches[icon.name]!;
    final source = versions.isEmpty
        ? '$fermanDesign (pending, Q11)'
        : sourceLabel(versions);
    out.writeln(
      '| `${icon.name}` | ${icon.origin.label} | '
      '${versions.isEmpty ? 'none' : versions.join(', ')} | $source | '
      '${directionalIcons.containsKey(icon.name) ? 'yes' : ''} |',
    );
  }
  return out.toString();
}
